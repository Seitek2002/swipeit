// Текст для чата друзей после брони (UX-аудит X01): в демо бронь видна только
// на телефоне гостя, и двое друзей купили бы одно и то же. Гость сам говорит
// остальным, что берёт. Ссылки в тексте нет — чат может быть с именинником,
// а вишлист друзья и так открывали. Имя без падежа (P11): «из вишлиста Тимур».
export const reservationChatText = ({
  ownerName,
  title,
}: {
  ownerName: string;
  title: string;
}): string => {
  const name = ownerName.trim();
  const gift = `Беру „${title.trim()}“`;
  return name
    ? `${gift} из вишлиста ${name} — не дублируйте`
    : `${gift} — не дублируйте`;
};
