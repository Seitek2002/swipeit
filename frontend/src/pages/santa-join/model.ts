// Приглашение, по которому уже не вступить (auto-tasks-pm-4 S04,
// auto-tasks-ux-6 Z01). Два разных случая — и разные тексты:
// - жеребьёвка прошла, а меня в игре нет. Чаще всего это опоздавший по
//   ссылке (в офисе на 20–30 человек таких больше всего) — ему не надо
//   ничего просить у организатора. Реже — участник, чей телефон потерял
//   профиль: Safari стёр данные, ссылку открыли во встроенном браузере,
//   сменили телефон. Для него — тихая кнопка, а не главный текст;
// - организатор убрал меня (сервер говорит это только мне — removed).
//   Сценария потерянного профиля нет: из игры убрали именно этот профиль.
// В обоих — куда идти дальше: свой вишлист или своя игра.
export type ClosedInvite = {
  // Показать ли «Я в этой игре, но телефон меня не узнал».
  lostProfile: boolean;
  text: string;
};

export const LOST_PROFILE_ACTION = "Я в этой игре, но телефон меня не узнал";

export const closedInvite = ({
  drawn,
  removed,
}: {
  drawn: boolean;
  removed: boolean;
}): ClosedInvite | null => {
  if (removed) {
    return {
      text: "Организатор убрал тебя из этой игры",
      lostProfile: false,
    };
  }
  if (drawn) {
    return {
      text: "Жеребьёвка уже прошла — новых участников не берём",
      lostProfile: true,
    };
  }
  return null;
};

// Пояснение в шторке потерянного профиля. Имя организатора — в скобках,
// чтобы не склонять (Z02).
export const lostProfileHint = (owner?: string) =>
  `Напиши организатору${owner ? ` (${owner})` : ""}: старый профиль уберут из игры, и твоего подопечного возьмёт другой Санта`;

// Сообщение организатору — его копирует кнопка в шторке. Имя — из поля «Как
// тебя звали в игре?» (подставлено имя из профиля): так организатор поймёт,
// какой профиль убрать. Поле пустое — без кавычек.
export const lostProfileMessage = ({
  name,
  title,
}: {
  name?: null | string;
  title: string;
}) => {
  const profile = name?.trim()
    ? `мой старый профиль «${name.trim()}»`
    : "мой старый профиль";
  return `Я в Тайном Санте «${title}», но телефон потерял мой профиль. Убери, пожалуйста, ${profile}, чтобы моего подопечного взял другой Санта`;
};
