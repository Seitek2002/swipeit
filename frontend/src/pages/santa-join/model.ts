// Приглашение в уже разыгранную игру, а я не в ней (auto-tasks-pm-4 S04).
// Чаще всего это не опоздавший, а участник, чей телефон потерял профиль:
// Safari стёр данные сайта, ссылку открыли во встроенном браузере, сменили
// телефон. Вместо тупика — что случилось и что сделать: организатор уберёт
// старый профиль (R05), и подопечного возьмёт другой Санта.
export const DRAWN_INVITE_TEXT =
  "Жеребьёвка уже прошла — новых участников не берём. Ты уже в этой игре, а телефон тебя не узнал? Напиши организатору: он уберёт старый профиль, и твоего подопечного возьмёт другой Санта";

// Сообщение организатору — его копирует кнопка. Имя — из моего профиля:
// так организатор поймёт, какой профиль убрать. Без имени — без кавычек.
export const lostProfileMessage = ({
  name,
  title,
}: {
  name?: null | string;
  title: string;
}) => {
  const profile = name?.trim()
    ? `мой старый профиль «${name.trim()}»`
    : "мой старый профиль";
  return `Я в Тайном Санте «${title}», но телефон потерял мой профиль. Убери, пожалуйста, ${profile}, чтобы моего подопечного взял другой Санта`;
};
