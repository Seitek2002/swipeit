import type { ApiMode } from "@/shared/api";

// «Что SwipeIt хранит» (auto-tasks-pm-4 S11). ЧЕРНОВИК PM, а не юридическая
// политика: политику и согласие пишет владелец с юристом до публичного
// запуска (BACKEND §14.4). Здесь — только то, что приложение правда делает,
// без обещаний сверх этого. Тексты — из задачи S11; «ввёл» и «отметил»
// переписаны без рода (правило текстов SwipeIt).

export type PrivacyText =
  | {
      deleteNote: string;
      items: string[];
      kind: "remote";
      note: string;
      title: string;
    }
  | { kind: "demo"; text: string };

const REMOTE_ITEMS = [
  "Твоё имя и цвет кружка.",
  "День рождения без года и твои даты.",
  "Вишлист, заметки и фото своих желаний.",
  "Твои «Хочу» и «Мимо» — так лента подстраивается.",
  "Брони. Кто забронировал подарок, владелец вишлиста не видит.",
  "Планы и игры, в которых ты участвуешь. Кому ты даришь в Тайном Санте, знаешь только ты — даже организатор этого не видит.",
];

// Только когда вход через Telegram включён (NEXT_PUBLIC_TELEGRAM_CLIENT_ID).
// В демо-режимах отправленный вишлист лежит в самой ссылке (`/w/?d=…`)
// вместе с именем и сообщением (auto-tasks-ux-6 Z06). Из задачи «Вишлист,
// который ты отправил» — переписано без рода.
const LINK_NOTE =
  "Отправленный вишлист лежит в самой ссылке — его увидит любой, у кого она есть.";

const TELEGRAM_ITEM =
  "Если войдёшь через Telegram — только номер аккаунта, без телефона и переписки.";

export const privacyText = (
  mode: ApiMode,
  { telegram }: { telegram: boolean },
): PrivacyText => {
  if (mode === "local") {
    return {
      kind: "demo",
      text: `Это демо: всё хранится в этом браузере. ${LINK_NOTE}`,
    };
  }
  // Локальная сеть — тоже демо, но данные на ноутбуке, а не в браузере
  // (решение Исполнителя: в задаче этого режима нет).
  if (mode === "lan") {
    return {
      kind: "demo",
      text: `Это демо в локальной сети: всё хранится на ноутбуке, где запущен SwipeIt. ${LINK_NOTE}`,
    };
  }
  return {
    kind: "remote",
    title: "Что SwipeIt знает о тебе",
    items: telegram ? [...REMOTE_ITEMS, TELEGRAM_ITEM] : REMOTE_ITEMS,
    note: "Телефон и почту не спрашиваем. Адрес устройства хранится в журнале сервера 14 дней.",
    deleteNote: "Удалить всё можно в профиле: «Удалить профиль».",
  };
};
